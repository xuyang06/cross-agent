#!/usr/bin/env python3
"""Make Claude Code and Codex share one set of instructions and skills.

    install.py [--vendor] [--local] REPO...   wire a project, existing or new
    install.py --system                        every project on this machine, now and later
    install.py --sync-global [--check]         regenerate ~/.codex/AGENTS.md from ~/.claude/rules

Never deletes content: text moves verbatim, skills move with `git mv`, and it overwrites only
files that carry its own marker. --local never touches a tracked file.
"""
import argparse
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SKILL_DIR))
import check_shared_config as check  # noqa: E402

SKILL_FILES = ("SKILL.md", "check_shared_config.py", "install.py")
LEGACY_STUB = "@../../../.agents/skills/cross-agent/SKILL.md"
LEGACY_STUB_COMMENT = """<!-- Adapter only. The canonical skill lives in .agents/skills/ so Codex and Copilot read
     the same file Claude Code does. Edit that one; this stub exists to point at it. -->"""
AGENTS_HEADER = """# Agent instructions

Shared by every coding agent in this repo: Codex reads this file directly, Claude Code through
the `@AGENTS.md` import in `CLAUDE.md`. Put project knowledge here. `CLAUDE.md` holds only that
import plus Claude-only content such as skill routing.
"""
RULE_MARKER = "<!-- written by cross-agent install.py --system; edits are overwritten -->"
GLOBAL_RULE = RULE_MARKER + """
# Shared agent setup

Claude Code and Codex both work on these projects, and neither can read the other's memory or
private config. Keep what they need in files both read:

- Project instructions live in `AGENTS.md`. `CLAUDE.md` is `@AGENTS.md` plus Claude-only
  content (skill routing). Never put project knowledge only in `CLAUDE.md`.
- Project skills live in `.agents/skills/<name>/`; `.claude/skills/<name>` is a symlink to it.
- Durable decisions go in `DECISIONS.md` in the repo, not in agent memory.
- A session-start hook wires broken projects itself. When it says it changed files, mention
  it so they get reviewed and committed. When it says it could not, fix what it names.
"""
HOOK = ('python3 "$HOME/.agents/skills/cross-agent/install.py" --sync-global --quiet; '
        'python3 "$HOME/.agents/skills/cross-agent/check_shared_config.py" --hook')
MARKER = "<!-- generated from ~/.claude/rules by cross-agent install.py --sync-global -->"
LEGACY_MARKER = "<!-- generated by ~/.codex/sync-claude-rules.sh -->"
SKIP_RULES = {"agents.md", "hooks.md", "performance.md"}  # Claude-only: subagents, hooks, models


def say(msg: str) -> None:
    print(f"  {msg}")


def write(path: Path, text: str) -> None:
    """Atomic, and safe when two session hooks write the same file at once."""
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)


def symlink(link: Path, target: str) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target)


def is_tracked(repo: Path, path: Path) -> bool:
    return check.git(repo, "ls-files", "--error-unmatch", "--", str(path)).returncode == 0


# ---------------------------------------------------------------- project instructions

def pointer_section(titles: list[str]) -> str:
    bullets = "".join(f"- {t}\n" for t in titles)
    return (f"{check.POINTER_HEADING}\n\nTools parse these sections in `CLAUDE.md` by heading, so they live "
            f"there.\nThey apply to every agent; read them in `CLAUDE.md`:\n\n{bullets}")


def wire_local(repo: Path) -> None:
    """Upstream clone: import from an untracked CLAUDE.local.md, touch nothing tracked."""
    local = repo / "CLAUDE.local.md"
    if is_tracked(repo, local):
        say("--local: CLAUDE.local.md is tracked here, so adding the import would change the repo; skipped")
        return
    old = local.read_text() if local.exists() else ""
    write(local, "@AGENTS.md\n" + (f"\n{old}" if old else ""))
    if (repo / ".git").exists() and check.git(repo, "check-ignore", "-q", "CLAUDE.local.md").returncode != 0:
        exclude = Path(check.git(repo, "rev-parse", "--git-path", "info/exclude").stdout.strip())
        exclude = exclude if exclude.is_absolute() else repo / exclude  # worktrees: .git is a file
        current = exclude.read_text() if exclude.exists() else ""
        write(exclude, current + ("" if current.endswith("\n") or not current else "\n") + "CLAUDE.local.md\n")
    say("CLAUDE.local.md imports AGENTS.md (local only, excluded from git)")


def wire_instructions(repo: Path, local: bool) -> None:
    """Migrate once: a repo where Claude already imports AGENTS.md is never rewritten."""
    agents, claude = repo / "AGENTS.md", repo / "CLAUDE.md"
    if claude.is_symlink():
        say("CLAUDE.md links to AGENTS.md, left alone" if check.same(claude, agents)
            else f"warning: CLAUDE.md is a symlink to {os.readlink(claude)}; point it at AGENTS.md by hand")
        return
    if check.claude_importer(repo) is not None:
        say("Claude already imports AGENTS.md; left alone" if agents.is_file()
            else "warning: a Claude file imports AGENTS.md, which does not exist; create it by hand")
        return
    if local:
        if agents.is_file():
            wire_local(repo)
        else:
            say("--local: no AGENTS.md to share, and creating one would change the repo; skipped")
        return
    secs = check.sections(claude.read_text()) if claude.is_file() else []
    moves = [t is None or check.heading_kind(t) == "shared" for t, _ in secs]
    current = agents.read_text() if agents.is_file() else AGENTS_HEADER
    moved = [b.strip() for (_, b), m in zip(secs, moves) if m and b.strip() and b.strip() not in current]
    if moved:
        current = current.rstrip() + "\n\n" + "\n\n".join(moved) + "\n"
        say(f"moved {len(moved)} shared CLAUDE.md section(s) into AGENTS.md, verbatim")
        stray = re.findall(r"(?:^|\s)(@[^\s`]+)", check.prose("\n".join(moved)))
        if stray:
            say(f"warning: Codex does not expand @imports; inline these in AGENTS.md: {stray}")
    tool = [t for (t, _), m in zip(secs, moves) if not m and check.heading_kind(t) == "tool"]
    if tool:
        current = current.rstrip() + "\n\n" + pointer_section(tool)
        say(f"kept tool-parsed sections in CLAUDE.md, listed in AGENTS.md: {tool}")
    write(agents, current)
    kept = "".join(b for (_, b), m in zip(secs, moves) if not m).strip()
    write(claude, "@AGENTS.md\n" + (f"\n{kept}\n" if kept else ""))
    say("CLAUDE.md imports AGENTS.md and keeps only Claude-side sections")


# ---------------------------------------------------------------- project skills

def vendor_skill(dest: Path) -> None:
    if dest.resolve() == SKILL_DIR:
        return  # running from this copy
    dest.mkdir(parents=True, exist_ok=True)
    for name in SKILL_FILES:
        shutil.copy2(SKILL_DIR / name, dest / name)


def is_legacy_stub(d: Path) -> bool:
    """Exactly our old adapter: one SKILL.md, only name/description frontmatter, our comment, the @ line."""
    if [p.name for p in d.iterdir()] != ["SKILL.md"]:
        return False
    m = re.match(r"---\n(.*?)\n---\n(.*)\Z", (d / "SKILL.md").read_text(), flags=re.S)
    front, body = (m.group(1), m.group(2)) if m else ("", (d / "SKILL.md").read_text())
    keys = {line.split(":", 1)[0] for line in front.splitlines() if line and not line[0].isspace()}
    return keys <= {"name", "description"} and body.replace(LEGACY_STUB_COMMENT, "", 1).strip() == LEGACY_STUB


def move(repo: Path, src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if check.git(repo, "mv", "--", str(src), str(dst)).returncode != 0:  # untracked: plain move
        shutil.move(str(src), str(dst))


def share_skills(repo: Path, vendor: bool) -> None:
    shared, claude = repo / ".agents/skills", repo / ".claude/skills"
    mine = shared / "cross-agent"
    if vendor:
        vendor_skill(mine)
        say("vendored .agents/skills/cross-agent/")
    elif mine.is_dir() and any(not (mine / n).exists() or (mine / n).read_bytes() != (SKILL_DIR / n).read_bytes()
                               for n in SKILL_FILES):
        say("note: the vendored cross-agent skill differs from this version; --vendor replaces it")
    if claude.is_symlink():
        return  # the whole directory is a link; the checker reports what it hides
    for skill in sorted(claude.glob("*/SKILL.md")) if claude.is_dir() else []:
        d = skill.parent
        if d.is_symlink():
            continue
        if is_legacy_stub(d) and (shared / d.name).is_dir():
            shutil.rmtree(d)
            say(f"replaced old stub .claude/skills/{d.name}")
        elif (shared / d.name).exists():
            say(f"warning: .claude/skills/{d.name} and .agents/skills/{d.name} both exist; merge by hand")
            continue
        else:
            move(repo, d, shared / d.name)
            say(f"moved .claude/skills/{d.name} -> .agents/skills/{d.name}")
    for canonical in sorted(shared.glob("*/SKILL.md")):
        link = claude / canonical.parent.name
        if not link.exists() and not link.is_symlink():
            symlink(link, f"../../.agents/skills/{canonical.parent.name}")
            say(f"linked .claude/skills/{canonical.parent.name}")


def install_project(repo: Path, vendor: bool, local: bool) -> bool:
    print(repo)
    wire_instructions(repo, local)
    if local:
        say("--local: skills left alone (moving or linking them changes the repo)")
    else:
        share_skills(repo, vendor)
    found = check.problems(repo)
    for p in found:
        say(f"FAIL {p}")
    say("ok: Claude Code and Codex load the same config" if not found else "fix the FAIL lines above")
    return not found


# ---------------------------------------------------------------- machine-wide

def rules_dir() -> Path:
    return Path.home() / ".claude/rules"


def render_rule(path: Path) -> str:
    """Strip frontmatter; turn Claude's `paths:` scoping into a line Codex can read."""
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, flags=re.S)
    if not m:
        return text.strip()
    globs = re.findall(r'^\s*-\s*"?([^"\n]+?)"?\s*$', m.group(1), flags=re.M)
    note = f"> Applies only to files matching: {', '.join(globs)}\n\n" if globs else ""
    return note + text[m.end():].strip()


def render_global() -> str:
    def order(p: Path) -> tuple:
        rel = p.relative_to(rules_dir())
        return (len(rel.parts) > 1, rel.parts[0] != "common", str(rel))
    rules = sorted((p for p in rules_dir().rglob("*.md") if p.name not in SKIP_RULES), key=order)
    header = (f"{MARKER}\n# Global instructions\n\n"
              "Generated from `~/.claude/rules`, the rules Claude Code loads in every project, so both\n"
              "agents work to the same standard. Do not edit: edit `~/.claude/rules`; a session-start\n"
              "hook regenerates this file.\n\n"
              "Named agents below (planner, tdd-guide, code-reviewer, security-reviewer, e2e-runner,\n"
              "build-error-resolver) are Claude Code subagents and are not available here. Do that\n"
              "step yourself.\n")
    return header + "".join(f"\n{render_rule(p)}\n" for p in rules)


def ours(path: Path, *markers: str) -> bool:
    """Missing, or written by this tool."""
    return not path.exists() or path.read_text().startswith(markers)


def sync_global(check_only: bool, quiet: bool) -> bool:
    out = check.codex_home() / "AGENTS.md"
    if not rules_dir().is_dir():
        if not quiet:
            say(f"no {rules_dir()}; no global rules to share")
        return True
    want = render_global()
    if check_only:
        problems = []
        override = check.codex_home() / "AGENTS.override.md"
        if override.exists() and override.read_text().strip():  # Codex uses the first non-empty one
            problems.append(f"{override} shadows {out}")
        if not out.exists() or out.read_text() != want:
            problems.append(f"{out} is stale or missing; run install.py --sync-global")
        for p in problems:
            print(f"FAIL {p}", file=sys.stderr)
        if not problems and not quiet:
            print(f"ok   {out} matches ~/.claude/rules")
        return not problems
    if not ours(out, MARKER, LEGACY_MARKER):
        print(f"{out} was not written by cross-agent; refusing to overwrite", file=sys.stderr)
        return False
    if not out.exists() or out.read_text() != want:
        write(out, want)
        if not quiet:
            say(f"wrote {out} ({len(want)} bytes)")
    return True


def add_hook(settings: Path, entry: dict) -> None:
    """Add a SessionStart hook entry once, keeping every other setting."""
    data = json.loads(settings.read_text()) if settings.exists() else {}
    hooks = data.get("hooks", {})
    existing = hooks.get("SessionStart", [])
    if any("cross-agent/" in h.get("command", "") for e in existing for h in e.get("hooks", [])):
        say(f"{settings}: hook already present")
        return
    if settings.exists():
        shutil.copy2(settings, settings.with_name(settings.name + ".cross-agent.bak"))
    updated = {**data, "hooks": {**hooks, "SessionStart": [*existing, entry]}}
    write(settings, json.dumps(updated, indent=2) + "\n")
    say(f"{settings}: added SessionStart hook")


def install_system() -> bool:
    home = Path.home()
    rule = rules_dir() / "cross-agent.md"
    if not ours(rule, RULE_MARKER):
        print(f"{rule} was not written by cross-agent; move it aside and rerun", file=sys.stderr)
        return False
    if not ours(check.codex_home() / "AGENTS.md", MARKER, LEGACY_MARKER):
        print(f"{check.codex_home() / 'AGENTS.md'} was not written by cross-agent; move it aside and rerun",
              file=sys.stderr)
        return False  # checked before any change, so a refusal leaves nothing half-installed
    vendor_skill(home / ".agents/skills/cross-agent")
    say("installed ~/.agents/skills/cross-agent (Codex reads it in every project)")
    link = home / ".claude/skills/cross-agent"
    if link.is_symlink() or not link.exists():
        if link.is_symlink():
            link.unlink()
        symlink(link, "../../.agents/skills/cross-agent")
        say("linked ~/.claude/skills/cross-agent (Claude reads it in every project)")
    else:
        say(f"warning: {link} is a real directory; replace it with a symlink to ../../.agents/skills/cross-agent")
    write(rule, GLOBAL_RULE)
    say(f"wrote {rule} (shared with Codex by the sync)")
    legacy = check.codex_home() / "sync-claude-rules.sh"
    if legacy.exists():  # a hook may still call it, so it stays until you remove it
        say(f"note: {legacy} is superseded by install.py --sync-global; delete it once nothing calls it")
    sync_global(check_only=False, quiet=False)
    command = {"type": "command", "command": HOOK, "timeout": 30}
    add_hook(home / ".claude/settings.json", {"hooks": [command]})
    add_hook(check.codex_home() / "hooks.json",
             {"matcher": "startup|resume", "hooks": [{**command, "statusMessage": "Checking shared agent config"}]})
    say("Codex asks you to review a new hook once before it runs; approve it.")
    return True


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("repos", nargs="*", type=Path)
    p.add_argument("--vendor", action="store_true", help="copy the skill into the repo, for teammates")
    p.add_argument("--local", action="store_true", help="change only untracked files (upstream clones)")
    p.add_argument("--system", action="store_true", help="install for every project on this machine")
    p.add_argument("--sync-global", action="store_true", help="regenerate ~/.codex/AGENTS.md")
    p.add_argument("--check", action="store_true", help="with --sync-global: verify, change nothing")
    p.add_argument("--quiet", action="store_true")
    a = p.parse_args(argv)
    if a.sync_global:
        return 0 if sync_global(a.check, a.quiet) else 1
    if a.system:
        return 0 if install_system() else 1
    if not a.repos:
        p.error("give a repo path, --system or --sync-global")
    if a.vendor and a.local:
        p.error("--vendor adds files to the repo; it cannot be combined with --local")
    bad = [r for r in a.repos if not r.is_dir()]
    if bad:
        p.error(f"not a directory: {bad}")
    if any(r.resolve() == SKILL_DIR.parents[2] for r in a.repos):
        p.error("refusing to install into the cross-agent repo itself")
    results = [install_project(r.resolve(), a.vendor, a.local) for r in a.repos]
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
